cp scripts/generate_static.py "scripts/generate_static.py.before-growth-patch-${STAMP}"
cp .github/workflows/static-seo-deploy.yml ".github/workflows/static-seo-deploy.yml.before-growth-patch-${STAMP}"

echo "[3/8] Patching static generator..."

python3 - <<'PY'
from pathlib import Path

p = Path("scripts/generate_static.py")
s = p.read_text(encoding="utf-8")

changes = 0

# ------------------------------------------------------------
# SAFETY 1: Never deploy an empty Firestore result.
# ------------------------------------------------------------
old = '''    try:
        posts = fetch_posts()
    except Exception as exc:
        print(f"ERROR: Firestore static build failed: {exc}", file=sys.stderr)
        return 2

    # Remove only files previously generated by this builder; hand-authored pages stay untouched.
'''
new = '''    try:
        posts = fetch_posts()
    except Exception as exc:
        print(f"ERROR: Firestore static build failed: {exc}", file=sys.stderr)
        return 2

    # SAFETY: an empty Firestore response is never treated as a valid build.
    # Otherwise cleanup_generated_files() could delete all generated article pages
    # and Firebase Hosting could deploy an empty article set.
    if not posts:
        print(
            "ERROR: Firestore returned ZERO published posts. "
            "Refusing to clean or deploy generated article pages.",
            file=sys.stderr,
        )
        return 3

    # SAFETY: duplicate slugs must never be silently dropped.
    slug_to_ids: dict[str, list[str]] = {}
    for p in posts:
        slug = slugify(p.get("slug"))
        if slug:
            slug_to_ids.setdefault(slug, []).append(str(p.get("id", "")))

    duplicate_slugs = {
        slug: ids for slug, ids in slug_to_ids.items()
        if len(ids) > 1
    }
    if duplicate_slugs:
        print("ERROR: Duplicate published article slugs detected:", file=sys.stderr)
        for slug, ids in sorted(duplicate_slugs.items()):
            print(f"  {slug}: {', '.join(ids)}", file=sys.stderr)
        print(
            "Refusing build so one published article cannot silently disappear.",
            file=sys.stderr,
        )
        return 4

    # Remove only files previously generated by this builder; hand-authored pages stay untouched.
'''
if old not in s:
    raise SystemExit("PATCH FAILED: main() safety anchor not found")
s = s.replace(old, new, 1)
changes += 1

# ------------------------------------------------------------
# SAFETY 2: Never silently skip duplicate slug in generation loop.
# ------------------------------------------------------------
old = '''    article_slugs: list[str] = []
    seen: set[str] = set()
    for p in posts:
        s = slugify(p.get("slug"))
        if not s or s in seen or s in RESERVED_SLUGS:
            continue
        (PUBLIC / f"{s}.html").write_text(article_page(p, posts), encoding="utf-8")
        article_slugs.append(s)
        seen.add(s)
'''
new = '''    article_slugs: list[str] = []
    seen: set[str] = set()
    for p in posts:
        s = slugify(p.get("slug"))

        if not s:
            print(
                f"WARNING: Published post {p.get('id', '')} has no usable slug; "
                "skipping that post.",
                file=sys.stderr,
            )
            continue

        if s in RESERVED_SLUGS:
            raise RuntimeError(
                f"Published post {p.get('id', '')} uses reserved slug '{s}'. "
                "Refusing build so the article cannot silently disappear."
            )

        if s in seen:
            raise RuntimeError(
                f"Duplicate generated slug '{s}'. Refusing build."
            )

        (PUBLIC / f"{s}.html").write_text(
            article_page(p, posts),
            encoding="utf-8",
        )
        article_slugs.append(s)
        seen.add(s)
'''
if old not in s:
    raise SystemExit("PATCH FAILED: article generation loop anchor not found")
s = s.replace(old, new, 1)
changes += 1

# ------------------------------------------------------------
# GROWTH 1: More homepage crawlable article links.
# 24 -> 36.
# ------------------------------------------------------------
old = 'for i, p in enumerate(posts[:24]):'
new = 'for i, p in enumerate(posts[:36]):'
if old not in s:
    raise SystemExit("PATCH FAILED: homepage 24-post anchor not found")
s = s.replace(old, new, 1)
changes += 1

# ------------------------------------------------------------
# GROWTH 2: More related internal links on every article.
# 6 -> 8.
# ------------------------------------------------------------
old = 'related = related_posts(p, posts)'
new = 'related = related_posts(p, posts, limit=8)'
if old not in s:
    raise SystemExit("PATCH FAILED: related-post anchor not found")
s = s.replace(old, new, 1)
changes += 1

# ------------------------------------------------------------
# GROWTH 3: Make the article's related section more explicit
# for users + crawlers without stuffing keywords.
# ------------------------------------------------------------
old = '<span class="eyebrow">YOU MAY ALSO LIKE</span><h2>Related Updates</h2>'
new = '<span class="eyebrow">MORE FROM EXAM DARPAN</span><h2>Related Updates</h2>'
if old not in s:
    raise SystemExit("PATCH FAILED: related heading anchor not found")
s = s.replace(old, new, 1)
changes += 1

# ------------------------------------------------------------
# GROWTH 4: Add a compact crawlable "latest updates" block
# to every article, immediately before the community CTA.
#
# This gives an article another route to newer pages.
# It is generated from the same published-post dataset.
# ------------------------------------------------------------
anchor = '''    related_html = ""
    if related:
'''
if anchor not in s:
    raise SystemExit("PATCH FAILED: related_html anchor not found")

# We only add helper once.
helper_marker = 'def article_latest_links('
if helper_marker not in s:
    insert_before = 'def article_page(p: dict[str, Any], posts: list[dict[str, Any]]) -> str:\\n'
    helper = r'''def article_latest_links(
    post: dict[str, Any],
    posts: list[dict[str, Any]],
    limit: int = 5,
) -> str:
    """Small crawlable list of recent published articles for article-to-article discovery."""
    current_id = post.get("id")
    current_slug = slugify(post.get("slug"))

    items: list[str] = []
    for other in posts:
        if other.get("id") == current_id:
            continue

        other_slug = slugify(other.get("slug"))
        if not other_slug or other_slug == current_slug:
            continue

        items.append(
            f'<li><a href="{esc(article_path(other_slug))}">'
            f'{esc(post_title(other))}</a></li>'
        )

        if len(items) >= limit:
            break

    if not items:
        return ""

    return (
        '<section class="article-latest-links card pad">'
        '<div class="section-title">'
        '<div><span class="eyebrow">LATEST UPDATES</span>'
        '<h2>नई Updates</h2></div>'
        '</div>'
        '<ul class="article-latest-list">'
        + "".join(items)
        + '</ul>'
        '</section>'
    )


'''
    if insert_before not in s:
        raise SystemExit("PATCH FAILED: article_page definition anchor not found")
    s = s.replace(insert_before, helper + insert_before, 1)
    changes += 1

# Add latest_html variable.
old = '''    related = related_posts(p, posts, limit=8)
    content = clean_article_content(p.get("content")) or "<p>इस article का content अभी उपलब्ध नहीं है।</p>"
'''
new = '''    related = related_posts(p, posts, limit=8)
    latest_links_html = article_latest_links(p, posts, limit=5)
    content = clean_article_content(p.get("content")) or "<p>इस article का content अभी उपलब्ध नहीं है।</p>"
'''
if old not in s:
    raise SystemExit("PATCH FAILED: article variable anchor not found")
s = s.replace(old, new, 1)
changes += 1

# Insert before final community card.
old = '''{related_html}
<section class="community-card">
'''
new = '''{related_html}
{latest_links_html}
<section class="community-card">
'''
if old not in s:
    raise SystemExit("PATCH FAILED: article latest-links insertion anchor not found")
s = s.replace(old, new, 1)
changes += 1

p.write_text(s, encoding="utf-8")

print(f"Generator patch applied: {changes} changes")
PY

echo "[4/8] Patching workflow verification..."

python3 - <<'PY'
from pathlib import Path

p = Path(".github/workflows/static-seo-deploy.yml")
s = p.read_text(encoding="utf-8")

changes = 0

# Better build logging + hard verification.
old = '''      - name: Verify generated SEO files
        run: |
          test -f public/sitemap.xml
          test -f public/robots.txt || true
          echo "Generated article pages:"
          find public -maxdepth 1 -type f -name "*.html" | wc -l
'''
