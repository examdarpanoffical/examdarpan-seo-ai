        run: |
          set -euo pipefail

          test -f public/sitemap.xml

          ARTICLE_COUNT="$(grep -rl --include="*.html" "EXAM-DARPAN-GENERATED-ARTICLE" public | wc -l | tr -d ' ')"
          SITEMAP_COUNT="$(grep -c "<loc>" public/sitemap.xml || true)"

          echo "Generated article pages: ${ARTICLE_COUNT}"
          echo "Sitemap URLs: ${SITEMAP_COUNT}"

          # A successful Firebase read must produce at least one article.
          test "${ARTICLE_COUNT}" -gt 0

          # Keep a machine-readable build summary in the Actions log.
          echo "BUILD_ARTICLE_COUNT=${ARTICLE_COUNT}"
          echo "BUILD_SITEMAP_COUNT=${SITEMAP_COUNT}"
'''
if old not in s:
    raise SystemExit("PATCH FAILED: workflow verification anchor not found")
s = s.replace(old, new, 1)
changes += 1

# Make the deploy output easier to diagnose.
old = '''      - name: Deploy Firebase Hosting
        env:
          GOOGLE_APPLICATION_CREDENTIALS_JSON: ${{ secrets.FIREBASE_SERVICE_ACCOUNT_JSON }}
        run: |
          printf '%s' "$GOOGLE_APPLICATION_CREDENTIALS_JSON" > /tmp/firebase-service-account.json
          export GOOGLE_APPLICATION_CREDENTIALS=/tmp/firebase-service-account.json
          firebase use examdarpan-dd963
          firebase deploy --only hosting --non-interactive
'''
new = '''      - name: Deploy Firebase Hosting
        env:
          GOOGLE_APPLICATION_CREDENTIALS_JSON: ${{ secrets.FIREBASE_SERVICE_ACCOUNT_JSON }}
        run: |
          set -euo pipefail

          printf '%s' "$GOOGLE_APPLICATION_CREDENTIALS_JSON" > /tmp/firebase-service-account.json
          export GOOGLE_APPLICATION_CREDENTIALS=/tmp/firebase-service-account.json

          firebase use examdarpan-dd963

          echo "Deploying generated Exam Darpan SEO build..."
          firebase deploy --only hosting --non-interactive
'''
if old not in s:
    raise SystemExit("PATCH FAILED: workflow deploy anchor not found")
s = s.replace(old, new, 1)
changes += 1

p.write_text(s, encoding="utf-8")

print(f"Workflow patch applied: {changes} changes")
PY

