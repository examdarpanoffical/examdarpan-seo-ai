echo
echo 'git add scripts/generate_static.py .github/workflows/static-seo-deploy.yml'
echo 'git commit -m "Strengthen article discovery and publish safety"'
echo 'git push origin main'
echo
echo "Backup files:"
echo "scripts/generate_static.py.before-growth-v3-${STAMP}"
